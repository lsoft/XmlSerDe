using System;

namespace XmlSerDe.Common
{
    /// <summary>
    /// Opt-in отказ на вводе, который XML 1.0 считает не-well-formed и который
    /// ядро по умолчанию молча превращает в POCO. Default (<see cref="None"/>) -
    /// быстрый POCO-путь: генератор для этих проверок не порождает кода вовсе.
    ///
    /// Ось независима от <see cref="XmlFeature"/>: та отвечает на вопрос
    /// "понимать ли эту конструкцию", эта - "отказать ли, если XML 1.0 её
    /// запрещает". Хост бывает с <see cref="XmlFeature.CData"/> и без стражей,
    /// и наоборот. Составных членов, включающих друг друга, здесь нет:
    /// у каждого стража своя точка вставки и своя цена.
    ///
    /// Синтаксис атрибута (<c>Name Eq AttValue</c>) членом этого перечисления
    /// не является и проверяется всегда: режима, в котором читать значение
    /// соседнего атрибута правильно, у ядра нет
    /// (docs/opt-in-xml-guards.md §5.1).
    /// </summary>
    [Flags]
    public enum XmlGuard
    {
        None = 0,

        /// <summary>
        /// Закрывающий тег сложного типа должен совпасть с открывающим, а тело
        /// не может кончиться концом ввода без этого тега. Без флага любой
        /// <c>&lt;/…&gt;</c> закрывает текущий класс, а отсутствие закрытия -
        /// успех с частично заполненным объектом.
        ///
        /// Скалярные тела сегодня сверяют имя всегда; переезжает ли эта сверка
        /// под флаг - решается замером (docs/opt-in-xml-guards.md §5.7). Чужое
        /// поддерево, уходящее в skip, имён не сверяет и с флагом.
        /// </summary>
        MatchingEndTags = 1 << 0,

        /// <summary>
        /// После корня допустим только Misc: пробелы XML S production
        /// (#x20 | #x9 | #xD | #xA), а у хоста с <see cref="XmlFeature.Markup"/> -
        /// ещё комментарии и processing instructions. Второй корень или мусор -
        /// ошибка, а не молча съеденный хвост.
        /// </summary>
        SingleRoot = 1 << 1,

        /// <summary>
        /// Два атрибута с одним qualified name на одной голове - ошибка
        /// (XML 1.0 WFC: Unique Att Spec). Без флага берётся первое совпадение.
        /// </summary>
        UniqueAttributes = 1 << 2,

        /// <summary>
        /// Строка, доехавшая до POCO (текст элемента, значение атрибута), должна
        /// состоять из Char XML 1.0 §2.2. Без флага U+0001 в строковом члене
        /// принимается. Не путать с <see cref="XmlFeature.CharGuard"/>: тот про
        /// сериализацию, этот про вход.
        /// </summary>
        IllegalChars = 1 << 3,

        /// <summary>
        /// Набор, достаточный чтобы native/compat отказывали на том же malformed
        /// вводе, что <c>System.Xml.Serialization.XmlSerializer</c> на
        /// поддерживаемом подмножестве. Это же значение автоматически получает
        /// compat-слой.
        /// </summary>
        SystemXmlCompatible =
            MatchingEndTags
            | SingleRoot
            | UniqueAttributes
            | IllegalChars,
    }
}
